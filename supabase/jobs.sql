-- Other jobs (work orders, lawn care, custom jobs) — same idea as the graffiti tracker, one table for all three tabs.
-- Run in the Supabase SQL editor. Safe to re-run. Photos go in the existing private "graffiti" bucket.

create table if not exists public.jobs (
  id               bigint generated by default as identity primary key,
  jtype            text not null check (jtype in ('workorders', 'lawn', 'otherjobs')),
  status           text not null default 'open' check (status in ('open', 'in_progress', 'done')),
  title            text not null,
  wo_number        text,
  city             text not null check (city in ('bozeman', 'helena')),
  address          text,
  lat              double precision,
  lng              double precision,
  description      text,
  notes            text,
  bill_mode        text not null default 'hourly' check (bill_mode in ('hourly', 'flat', 'hourly_materials')),
  price_cents      integer check (price_cents is null or (price_cents >= 0 and price_cents <= 100000000)),
  materials        jsonb not null default '[]'::jsonb,
  before_photo     text,
  after_photo      text,
  started_at       timestamptz,
  finished_at      timestamptz,
  done_at          timestamptz,
  duration_min     integer check (duration_min is null or (duration_min >= 0 and duration_min <= 1440)),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  created_by       text not null,
  created_by_name  text,
  done_by_name     text
);

create index if not exists jobs_type_status_idx on public.jobs (jtype, status);
create index if not exists jobs_type_done_idx   on public.jobs (jtype, done_at) where done_at is not null;

-- Only the server (service role) touches this table; nobody gets direct access from the browser.
alter table public.jobs enable row level security;
