-- Patrol tracking + coverage (safe to re-run).
-- patrol_points: where a crew phone was while "Patrolling" was switched on (one point about every 80 m driven).
--   Kept 90 days; the coverage page deletes older points.
-- coverage_cells: for each ~300 m grid cell, the last time any crew drove through it (no history, just the latest).
create table if not exists public.patrol_points (
  id         bigint generated by default as identity primary key,
  user_id    text             not null,
  user_name  text,
  session    text             not null,
  lat        double precision not null,
  lng        double precision not null,
  acc        integer,
  at         timestamptz      not null,
  created_at timestamptz      not null default now()
);
create index if not exists patrol_points_at on public.patrol_points (at);
create index if not exists patrol_points_session_at on public.patrol_points (session, at);

create table if not exists public.coverage_cells (
  cell     text        primary key,
  city     text        not null check (city in ('bozeman', 'helena')),
  last_at  timestamptz not null,
  last_by  text
);
create index if not exists coverage_cells_city on public.coverage_cells (city);

-- Only the server (service role) touches these; nobody gets direct access from the browser.
alter table public.patrol_points  enable row level security;
alter table public.coverage_cells enable row level security;
